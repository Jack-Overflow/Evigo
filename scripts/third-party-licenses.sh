#!/bin/sh
set -eu

dashboard_licenses=internal/api/static/.vite/license.md
if [ ! -f "$dashboard_licenses" ]; then
	printf '%s\n' "$dashboard_licenses is missing; build the dashboard first." >&2
	exit 1
fi

separator='========================================================================'

license_files() {
	find "$1" -maxdepth 1 -type f \( -iname 'licen[cs]e*' -o -iname 'copying*' -o -iname 'notice*' -o -iname 'patents*' \) | sort
}

print_notice() {
	title=$1
	directory=$2
	files=$(license_files "$directory")
	if [ -z "$files" ]; then
		printf '%s\n' "No license file found for $title." >&2
		exit 1
	fi
	printf '\n%s\n%s\n' "$separator" "$title"
	for file in $files; do
		printf '\n'
		cat "$file"
	done
}

cat <<'EOF'
Evigo
Copyright 2026 Jack Baker
Licensed under the Apache License, Version 2.0. See LICENSE.

Third-party notices for the Go modules and dashboard packages built into this
copy of Evigo. Generated by scripts/third-party-licenses.sh at build time.
EOF

print_notice "Go standard library $(go env GOVERSION)" "$(go env GOROOT)"

modules=$(
	for architecture in amd64 arm64; do
		CGO_ENABLED=0 GOOS=linux GOARCH=$architecture \
			go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/evigo
	done | sort -u
)
printf '%s\n' "$modules" | while read -r path version directory; do
	print_notice "$path $version" "$directory"
done

printf '\n%s\n' "$separator"
cat "$dashboard_licenses"
printf '\n'
cat web/THIRD_PARTY_LICENSES
